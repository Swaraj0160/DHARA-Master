export interface PuzzleOption {
  id: string;
  text: string;
  isCorrect: boolean;
  explanation?: string;
}

export type PuzzleType = 'multiple_choice' | 'clue_hunt' | 'decision';

export interface ClueItem {
  id: string;
  name: string;
  category: string;
  icon: string;
  material: string;
  inspectionNotes: string;
  isTarget: boolean;
  whyMatters: string;
}

export interface Puzzle {
  id: string;
  chapterId: string;
  type: PuzzleType;
  prompt: string;
  context?: string;
  speaker?: string;
  hint?: string;
  options: PuzzleOption[];
  xpReward?: number; // Defaults to XP_CONFIG.PUZZLE_CORRECT
  clues?: ClueItem[];
  decisionImpact?: {
    summary: string;
  };
}

export interface Chapter {
  id: string;
  cityId: string;
  chapterNumber: number;
  title: string;
  locationName: string;
  description: string;
  coordinates: { x: number; y: number }; // Percentage (0-100) on the city map
  maxStars: number;
  puzzles: Puzzle[];
}

export interface City {
  id: string;
  name: string;
  subtitle: string;
  description: string;
  artwork: string;
  requiredStars: number; // Global stars threshold to unlock
  coordinates: { x: number; y: number }; // Percentage (0-100) on the world map
  region: string;
  era: string;
  chapters: Chapter[];
}

export const XP_CONFIG = {
  PUZZLE_CORRECT: 100,
  PUZZLE_INCORRECT: 0,
  XP_PER_LEVEL: 1000,
} as const;

// Calculate Level from Total XP: floor(totalXP / 1000)
export function calculateLevel(totalXP: number): number {
  return Math.floor(Math.max(0, totalXP) / XP_CONFIG.XP_PER_LEVEL);
}

// Calculate Chapter Stars from correct answers and total questions:
// floor((correct / total) * 3) clamped to 0..3
export function calculateChapterStars(correct: number, total: number): number {
  if (total <= 0) return 0;
  const ratio = Math.max(0, correct) / total;
  const rawStars = Math.floor(ratio * 3);
  return Math.max(0, Math.min(3, rawStars));
}

